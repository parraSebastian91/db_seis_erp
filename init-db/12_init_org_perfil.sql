SET search_path TO public, core;

-- ---------------------------------------------------------------------------
-- 1. CATÁLOGOS COMPARTIDOS
-- ---------------------------------------------------------------------------

-- Países (ISO 3166-1 alpha-2 + nombre para UI)
CREATE TABLE IF NOT EXISTS core.pais (
    pais_id   SERIAL          PRIMARY KEY,
    codigo    CHAR(2)         UNIQUE NOT NULL,   -- 'CL', 'PE', 'AR', 'MX' …
    nombre    VARCHAR(80)     NOT NULL,
    activo    BOOLEAN         DEFAULT true
);

-- Divisiones administrativas de nivel 1 (región, estado, provincia, departamento)
-- Genérico para cualquier país. "nivel_nombre" describe cómo se llama en ese país.
CREATE TABLE IF NOT EXISTS core.division_admin (
    division_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pais_id       INT            NOT NULL REFERENCES core.pais(pais_id),
    codigo        VARCHAR(10)    NOT NULL,            -- 'RM', 'BIO', 'LIM' …
    nombre        VARCHAR(120)   NOT NULL,
    nivel_nombre  VARCHAR(40)    NOT NULL DEFAULT 'Región', -- 'Región','Estado','Provincia'
    activo        BOOLEAN        DEFAULT true,
    UNIQUE (pais_id, codigo)
);

-- Catálogo de productos/servicios financieros que puede ofrecer una financiera
CREATE TABLE IF NOT EXISTS core.producto_financiero (
    producto_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(40)    UNIQUE NOT NULL,
    nombre        VARCHAR(120)   NOT NULL,
    descripcion   TEXT,
    aplica_a      VARCHAR(20)[]  NOT NULL DEFAULT ARRAY['FINANCIADORA','BROKER'],
    activo        BOOLEAN        DEFAULT true
);

-- ---------------------------------------------------------------------------
-- 2. PERFIL EXTENDIDO DE ORGANIZACIÓN
--    Una fila por organización (1:1 con core.organizacion)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS core.organizacion_perfil (
    -- PK / FK
    organizacion_id         BIGINT  PRIMARY KEY
                            REFERENCES core.organizacion(organizacion_id) ON DELETE CASCADE,

    -- ── Estado del cuestionario ──────────────────────────────────────────
    onboarding_completo     BOOLEAN         NOT NULL DEFAULT false,
    onboarding_completado_at TIMESTAMPTZ,

    -- ── Contrato digital ─────────────────────────────────────────────────
    -- NOTA: paises_operacion se DERIVA de organizacion_zona_operacion
    -- (ver vista v_organizacion_perfil_completo). No se almacena aquí
    -- para evitar inconsistencias. El wizard pobla las zonas directamente.
    tiene_contrato_digital  BOOLEAN         NOT NULL DEFAULT false,
    plataforma_firma        VARCHAR(80),            -- 'DocuSign','Mifiel','FirmaVirtual',…

    -- ── Tamaño / capacidad (relevante para FINANCIADORA) ─────────────────
    -- Monto mínimo por operación, en USD para normalizar entre monedas
    monto_min_usd           NUMERIC(18,2),
    -- Monto máximo por operación
    monto_max_usd           NUMERIC(18,2),
    -- Plazo típico de pago en días
    plazo_tipico_dias       INT,

    -- ── Datos de contacto de operaciones (centralizado aquí) ─────────────
    email_operaciones       VARCHAR(255),
    telefono_operaciones    VARCHAR(30),

    -- ── Preferencias de notificación ─────────────────────────────────────
    notif_email             BOOLEAN         NOT NULL DEFAULT true,
    notif_whatsapp          BOOLEAN         NOT NULL DEFAULT false,
    notif_sms               BOOLEAN         NOT NULL DEFAULT false,

    -- ── Campos adicionales libres (extensibilidad sin nueva migración) ────
    metadata                JSONB           NOT NULL DEFAULT '{}',

    created_at              TIMESTAMPTZ     NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ     NOT NULL DEFAULT now(),

    CONSTRAINT ck_montos
        CHECK (monto_min_usd IS NULL OR monto_max_usd IS NULL
               OR monto_min_usd <= monto_max_usd)
);

-- ---------------------------------------------------------------------------
-- 3. ZONAS DE OPERACIÓN (N:N organización ↔ división administrativa)
--    Permite seleccionar regiones/estados concretos dentro de cada país.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS core.organizacion_zona_operacion (
    organizacion_id     BIGINT   NOT NULL REFERENCES core.organizacion(organizacion_id) ON DELETE CASCADE,
    division_id         BIGINT   NOT NULL REFERENCES core.division_admin(division_id),
    es_principal        BOOLEAN  NOT NULL DEFAULT false,

    -- Trazabilidad: cómo se originó esta zona
    --   'DECLARADA'          → el usuario la marcó explícitamente en el wizard
    --   'DERIVADA_DIRECCION' → se auto-generó desde una dirección física
    origen              VARCHAR(25) NOT NULL DEFAULT 'DECLARADA'
                        CHECK (origen IN ('DECLARADA', 'DERIVADA_DIRECCION')),

    -- Cuando origen = 'DERIVADA_DIRECCION', traza a la dirección que la generó.
    -- ON DELETE SET NULL: si se elimina la dirección la zona PERSISTE
    -- (la org puede seguir operando allí aunque cierre esa sucursal).
    direccion_origen_id BIGINT   NULL
                        REFERENCES core.organizacion_direccion(organizacion_direccion_id)
                        ON DELETE SET NULL,

    PRIMARY KEY (organizacion_id, division_id)
);

COMMENT ON TABLE core.organizacion_zona_operacion IS
    'Cobertura operativa declarada por la organización. '
    'Una zona puede existir sin dirección física (campo declarado en el wizard) '
    'o derivarse automáticamente de una dirección vía trigger.';

-- ---------------------------------------------------------------------------
-- 4. PRODUCTOS QUE MANEJA LA ORGANIZACIÓN (N:N)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS core.organizacion_producto (
    organizacion_id  BIGINT  NOT NULL REFERENCES core.organizacion(organizacion_id)  ON DELETE CASCADE,
    producto_id      BIGINT  NOT NULL REFERENCES core.producto_financiero(producto_id),
    activo           BOOLEAN NOT NULL DEFAULT true,
    -- condiciones específicas de esta org para este producto (tasas, límites, etc.)
    condiciones      JSONB   NOT NULL DEFAULT '{}',
    PRIMARY KEY (organizacion_id, producto_id)
);

