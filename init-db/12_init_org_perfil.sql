-- ---------------------------------------------------------------------------
-- 6. TRIGGER: actualizar updated_at automáticamente
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION core.set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER trg_organizacion_perfil_updated_at
    BEFORE UPDATE ON core.organizacion_perfil
    FOR EACH ROW EXECUTE FUNCTION core.set_updated_at();

-- ---------------------------------------------------------------------------
-- 7. VISTA RESUMEN (útil para el BFF y reportes)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE VIEW core.v_organizacion_perfil_completo AS
SELECT
    o.organizacion_id,
    o.organizacion_uuid,
    o.razon_social,
    o.tipo_participante,
    p.onboarding_completo,
    p.onboarding_completado_at,
    p.tiene_contrato_digital,
    p.plataforma_firma,
    p.monto_min_usd,
    p.monto_max_usd,
    p.plazo_tipico_dias,
    p.email_operaciones,
    p.notif_email,
    p.notif_whatsapp,
    p.notif_sms,

    -- Países de operación (DERIVADOS de las zonas, no almacenados)
    COALESCE(
        ARRAY_AGG(DISTINCT pai.codigo) FILTER (WHERE pai.codigo IS NOT NULL),
        '{}'
    ) AS paises_operacion,

    -- Zonas de operación: nombre de división + origen
    COALESCE(
        ARRAY_AGG(DISTINCT da.nombre) FILTER (WHERE da.nombre IS NOT NULL),
        '{}'
    ) AS zonas_operacion,

    -- Zonas declaradas manualmente (no derivadas de dirección)
    COALESCE(
        ARRAY_AGG(DISTINCT da.nombre)
            FILTER (WHERE da.nombre IS NOT NULL AND ozo.origen = 'DECLARADA'),
        '{}'
    ) AS zonas_declaradas,

    -- Productos activos (array de códigos)
    COALESCE(
        ARRAY_AGG(DISTINCT pf.codigo) FILTER (WHERE pf.codigo IS NOT NULL AND op.activo),
        '{}'
    ) AS productos_activos,

    p.metadata,
    p.updated_at AS perfil_actualizado_at

FROM core.organizacion o
LEFT JOIN core.organizacion_perfil          p   ON p.organizacion_id   = o.organizacion_id
LEFT JOIN core.organizacion_zona_operacion  ozo ON ozo.organizacion_id = o.organizacion_id
LEFT JOIN core.division_admin               da  ON da.division_id      = ozo.division_id
LEFT JOIN core.pais                         pai ON pai.pais_id         = da.pais_id
LEFT JOIN core.organizacion_producto        op  ON op.organizacion_id  = o.organizacion_id
LEFT JOIN core.producto_financiero          pf  ON pf.producto_id      = op.producto_id

GROUP BY
    o.organizacion_id, o.organizacion_uuid, o.razon_social, o.tipo_participante,
    p.onboarding_completo, p.onboarding_completado_at,
    p.tiene_contrato_digital, p.plataforma_firma,
    p.monto_min_usd, p.monto_max_usd, p.plazo_tipico_dias,
    p.email_operaciones, p.notif_email, p.notif_whatsapp, p.notif_sms,
    p.metadata, p.updated_at;

-- ---------------------------------------------------------------------------
-- 8. RELACIÓN organizacion_direccion ↔ division_admin
--    Vincula la dirección física de la org con el catálogo geográfico normalizado
--    y auto-sincroniza organizacion_zona_operacion via trigger.
-- ---------------------------------------------------------------------------

-- 8a. FK desde organizacion_direccion hacia division_admin (nullable).
--     Mantiene region/pais TEXT para backward-compat y para países sin catálogo cargado.
ALTER TABLE core.organizacion_direccion
    ADD COLUMN IF NOT EXISTS division_id BIGINT
        REFERENCES core.division_admin(division_id) ON DELETE SET NULL;

COMMENT ON COLUMN core.organizacion_direccion.division_id IS
    'FK al catálogo normalizado de divisiones administrativas. '
    'Cuando se informa, region y pais TEXT quedan como copia legible de respaldo.';

-- Índice para búsquedas por zona geográfica
CREATE INDEX IF NOT EXISTS idx_org_dir_division
    ON core.organizacion_direccion (division_id)
    WHERE division_id IS NOT NULL;

-- 8b. Trigger: al insertar / actualizar una dirección con division_id,
--     registra automáticamente la zona en organizacion_zona_operacion.
--     - INSERT:  si la fila nueva tiene division_id, garantiza la zona.
--     - UPDATE:  si cambia division_id, agrega la nueva zona (la antigua se deja
--                intacta porque la org puede seguir operando allí).
--     - DELETE:  no elimina la zona (puede haber otras direcciones en esa región).

CREATE OR REPLACE FUNCTION core.sync_zona_desde_direccion()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.division_id IS NOT NULL THEN
        INSERT INTO core.organizacion_zona_operacion
            (organizacion_id, division_id, es_principal, origen, direccion_origen_id)
        VALUES
            (NEW.organizacion_id, NEW.division_id, NEW.es_principal,
             'DERIVADA_DIRECCION', NEW.organizacion_direccion_id)
        ON CONFLICT (organizacion_id, division_id) DO UPDATE SET
            -- Promover a principal si la dirección lo indica
            es_principal        = EXCLUDED.es_principal
                                  OR core.organizacion_zona_operacion.es_principal,
            -- No sobreescribir la traza si el usuario ya la declaró manualmente
            direccion_origen_id = CASE
                WHEN core.organizacion_zona_operacion.origen = 'DECLARADA'
                    THEN core.organizacion_zona_operacion.direccion_origen_id
                ELSE EXCLUDED.direccion_origen_id
            END;
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER trg_sync_zona_desde_direccion
    AFTER INSERT OR UPDATE OF division_id, es_principal
    ON core.organizacion_direccion
    FOR EACH ROW EXECUTE FUNCTION core.sync_zona_desde_direccion();

-- 8c. Función auxiliar: poblar division_id en direcciones existentes
--     que ya tienen pais + region coincidentes con el catálogo.
--     Ejecutar manualmente una vez después de cargar la migración.
CREATE OR REPLACE FUNCTION core.backfill_division_en_direcciones()
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE
    filas_actualizadas INTEGER;
BEGIN
    UPDATE core.organizacion_direccion od
    SET division_id = da.division_id
    FROM core.division_admin da
    JOIN core.pais p ON p.pais_id = da.pais_id
    WHERE od.division_id IS NULL
      AND od.pais   = p.codigo
      AND (
          -- coincidencia exacta de nombre
          od.region = da.nombre
          -- o coincidencia de código (ej: 'RM' en el campo region)
          OR od.region = da.codigo
      );

    GET DIAGNOSTICS filas_actualizadas = ROW_COUNT;
    RETURN filas_actualizadas;
END;
$$;

COMMENT ON FUNCTION core.backfill_division_en_direcciones() IS
    'Rellena division_id en filas históricas de organizacion_direccion '
    'que tengan pais + region coincidentes con el catálogo. '
    'Retorna el número de filas actualizadas.';

