-- Solo una dirección principal por tipo dentro de la organización
CREATE UNIQUE INDEX uq_org_dir_principal_por_tipo
ON core.organizacion_direccion (organizacion_id, tipo_direccion_id)
WHERE es_principal = true;

CREATE TRIGGER tr_check_unica_direccion_tributaria
BEFORE INSERT OR UPDATE ON core.organizacion_direccion
FOR EACH ROW
EXECUTE PROCEDURE core.tr_check_unica_direccion_tributaria();

