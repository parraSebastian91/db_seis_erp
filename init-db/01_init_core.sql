-- 3. ESTRUCTURA EMPRESARIAL
CREATE TABLE core.organizacion (
    organizacion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_uuid UUID DEFAULT gen_random_uuid() UNIQUE NOT NULL,
    razon_social VARCHAR(255) NOT NULL,

    -- Clasificación
    tipo_organizacion VARCHAR(20) NOT NULL DEFAULT 'JURIDICA', -- JURIDICA | PERSONA_NATURAL

    -- Identificación tributaria (obligatoria para JURIDICA)
    rut VARCHAR(12),
    dv CHAR(1),

    giro TEXT,
    activo BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now(),

    CONSTRAINT ck_organizacion_tipo
        CHECK (tipo_organizacion IN ('JURIDICA', 'PERSONA_NATURAL')),
    CONSTRAINT ck_organizacion_identificacion
        CHECK (
            (tipo_organizacion = 'JURIDICA' AND rut IS NOT NULL AND dv IS NOT NULL)
            OR (tipo_organizacion = 'PERSONA_NATURAL')
        ),
    UNIQUE(rut, dv)
);

ALTER TABLE core.organizacion 
ADD COLUMN tipo_participante varchar(30) DEFAULT 'CEDENTE'
CHECK (tipo_participante IN ('CEDENTE', 'FINANCIADORA'));

CREATE TABLE core.organizacion_attachments (
    organizacion_id UUID REFERENCES core.organizacion(organizacion_uuid),
    media_id UUID, -- FK a media.media_assets se agrega en 07_init_media.sql
    sort_order INT,
    PRIMARY KEY (organizacion_id, media_id)
);

-- Catálogo de tipos de dirección organizacional
CREATE TABLE core.tipo_direccion_organizacion (
    tipo_direccion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) UNIQUE NOT NULL, -- TRIBUTARIA, CASA_MATRIZ, SUCURSAL, BODEGA, ATENCION
    nombre VARCHAR(80) NOT NULL
);

-- Direcciones por organización (N:1)
CREATE TABLE core.organizacion_direccion (
    organizacion_direccion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizacion_id BIGINT NOT NULL REFERENCES core.organizacion(organizacion_id) ON DELETE CASCADE,
    tipo_direccion_id BIGINT NOT NULL REFERENCES core.tipo_direccion_organizacion(tipo_direccion_id),

    -- Dirección estructurada (mejor para reportes/impuestos)
    calle VARCHAR(150) NOT NULL,
    numero VARCHAR(20),
    depto_oficina VARCHAR(30),
    comuna VARCHAR(80),
    ciudad VARCHAR(80),
    region VARCHAR(80),
    codigo_postal VARCHAR(20),
    pais CHAR(2) NOT NULL DEFAULT 'CL',

    referencia TEXT,
    es_principal BOOLEAN DEFAULT false,
    activo BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- Relación N:N Organizaciones <-> Contactos
CREATE TABLE core.organizacion_contacto (
    organizacion_id BIGINT REFERENCES core.organizacion(organizacion_id) ON DELETE CASCADE,
    contacto_id BIGINT REFERENCES identity.contacto(contacto_id) ON DELETE CASCADE,
    cargo VARCHAR(100),
    es_principal BOOLEAN DEFAULT false,
    PRIMARY KEY (organizacion_id, contacto_id)
);

ALTER TABLE core.organizacion_contacto
ADD COLUMN tipo_relacion varchar(30) DEFAULT 'REFERENCIA'
CHECK (tipo_relacion IN (
    'REFERENCIA',       -- contacto general
    'PROVEEDOR',        -- proveedor de servicios
    'FACTURACION',      -- contacto para temas de factura
    'LEGAL',            -- representante legal
    'COMERCIAL'         -- ejecutivo comercial externo
));

-- 4. JERARQUÍAS Y GRUPOS DE TRABAJO
CREATE TABLE core.grupo_trabajo (
    grupo_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    nombre VARCHAR(100) NOT NULL,
    descripcion TEXT,
    lider_usuario_uuid UUID REFERENCES identity.usuario(usuario_uuid), -- Jefe del grupo
    organizacion_id UUID NOT NULL REFERENCES core.organizacion(organizacion_uuid) ON DELETE CASCADE,
    activo BOOLEAN DEFAULT true,
    grupo_metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE core.grupo_miembro (
    miembro_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    grupo_id UUID NOT NULL REFERENCES core.grupo_trabajo(grupo_id) ON DELETE CASCADE,
    usuario_uuid UUID NOT NULL REFERENCES identity.usuario(usuario_uuid) ON DELETE CASCADE,
    -- Recursividad: apunta a otro miembro del mismo grupo
    jefe_directo_id UUID REFERENCES core.grupo_miembro(miembro_id), 
    cargo_en_grupo VARCHAR(100),
    grupo_metadata JSONB DEFAULT '{}'::jsonb,
    fecha_ingreso TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now(),
    active BOOLEAN DEFAULT true,
    UNIQUE(grupo_id, usuario_uuid) -- Un usuario solo puede ser miembro una vez por grupo
);

-- Relación N:N Organizaciones <-> Sistemas
CREATE TABLE core.organizacion_sistema (
    organizacion_id BIGINT REFERENCES core.organizacion(organizacion_id) ON DELETE CASCADE,
    sistema_id BIGINT REFERENCES identity.sistema(sistema_id) ON DELETE CASCADE,
    fecha_activacion DATE DEFAULT CURRENT_DATE,
    PRIMARY KEY (organizacion_id, sistema_id)
);

